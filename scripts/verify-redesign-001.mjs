import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { preview } from "vite";
import { execFileSync } from "node:child_process";
import { chromium } from "playwright";

// Built production evidence. Full regression and independent exact-head review remain separate.
const inspectedHead = execFileSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const out = "docs/screenshots/redesign-001";
await mkdir(out, { recursive: true });
const server = await preview({ preview: { host: "127.0.0.1", port: 5192, strictPort: true } });
const browser = await chromium.launch({ headless: true, executablePath: process.env.BEYOND_BROWSER_EXECUTABLE || "/usr/bin/chromium" });
const evidence = [];
try {
  for (const width of [320, 360, 390, 412]) {
    const context = await browser.newContext({ viewport: { width, height: 844 }, timezoneId: "America/Chicago", reducedMotion: "reduce" });
    const page = await context.newPage();
    const errors = []; page.on("pageerror", (error) => errors.push(error.message));
    await page.clock.install({ time: new Date("2026-10-12T17:10:00-05:00") });
    await page.goto("http://127.0.0.1:5192/neo-beyond-lohnes/");
    await page.getByRole("heading", { name: "Mode not set", exact: true }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: `${out}/${width}-fresh-install.png` });
    await page.getByRole("button", { name: "START DAY", exact: true }).click();
    await page.getByRole("button", { name: "CHECK IN", exact: true }).click();
    const sheet = page.getByRole("dialog", { name: "CHECK IN", exact: true });
    await sheet.getByRole("group", { name: "Energy", exact: true }).getByRole("button", { name: "3", exact: true }).click();
    await page.screenshot({ path: `${out}/${width}-check-in.png` });
    await sheet.getByRole("button", { name: "CLOSE", exact: true }).click();
    for (const [name, phase] of [["PREP", "PRE_WORK"], ["ON SHIFT", "SCHEDULED_SHIFT"], ["RECOVER", "EXPECTED_POST_WORK"], ["OFF DUTY", "OFF"]]) {
      await page.getByRole("button", { name: /Mode .*Change mode/ }).click();
      await page.getByRole("dialog").getByRole("button", { name: new RegExp(`^${name}`) }).click();
      await page.waitForFunction((phase) => document.querySelector(".mode-header")?.dataset.mode === phase, phase);
      await page.evaluate(() => { for (const animation of document.getAnimations()) { if (animation.effect?.getComputedTiming().iterations === Infinity) animation.pause(); else animation.finish(); } window.scrollTo(0, 0); });
      const sections = await page.locator(".redesign-today > section").evaluateAll((nodes) => nodes.map((node) => node.getAttribute("aria-label")));
      // FIELD-AUTHORITY-001: no separate check-in section; with no guidance, logging leads.
      assert.deepEqual(sections, ["Day mode", "Log", "Next action", "Today's numbers"]);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      await page.screenshot({ path: `${out}/${width}-${phase.toLowerCase()}.png`, fullPage: true });
    }
    await page.getByRole("button", { name: "Log a meal", exact: true }).click();
    await page.getByRole("button", { name: "New meal", exact: true }).click();
    const newMeal = page.getByRole("dialog", { name: "NEW MEAL", exact: true });
    await newMeal.getByRole("textbox", { name: "New meal name" }).fill("Shift dinner");
    await newMeal.getByRole("spinbutton", { name: "New meal Calories", exact: true }).fill("600");
    await newMeal.getByRole("spinbutton", { name: "New meal Protein (g)", exact: true }).fill("40");
    await newMeal.getByRole("checkbox", { name: "Save for next time" }).check();
    await page.screenshot({ path: `${out}/${width}-new-meal.png` });
    await newMeal.getByRole("button", { name: "LOG", exact: true }).click();
    await page.locator(".record-receipt").waitFor();
    await page.getByRole("button", { name: "DISMISS", exact: true }).click();
    await page.waitForFunction(() => !history.state?.recordSheet);
    await page.getByRole("button", { name: "Log a meal", exact: true }).click();
    await page.getByRole("button", { name: "Log Shift dinner", exact: true }).waitFor();
    await page.screenshot({ path: `${out}/${width}-meal.png` });
    await page.getByRole("button", { name: "Servings for Shift dinner", exact: true }).click();
    const portion = await page.locator("dialog[open]").elementHandle();
    await page.getByRole("button", { name: "0.5 servings", exact: true }).click();
    assert.ok(await portion.evaluate((node) => node.isConnected && node.open));
    await page.screenshot({ path: `${out}/${width}-servings.png` });
    await page.getByRole("button", { name: "BACK TO MY MEALS", exact: true }).click();
    await page.getByRole("button", { name: "QUICK ADD", exact: true }).click();
    await page.screenshot({ path: `${out}/${width}-quick-add.png` });
    await page.getByRole("dialog").getByRole("button", { name: "CLOSE", exact: true }).click();
    await page.waitForFunction(() => !history.state?.recordSheet);
    for (const kind of ["LOG", "SLEEP", "BODYWEIGHT", "NOTE", "URGE"]) {
      await page.getByRole("button", { name: "Open LOG", exact: true }).click();
      if (kind !== "LOG") await page.getByRole("dialog").getByRole("button", { name: kind, exact: true }).click();
      await page.screenshot({ path: `${out}/${width}-${kind.toLowerCase()}.png` });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      await page.getByRole("dialog").getByRole("button", { name: "CLOSE", exact: true }).click();
      await page.waitForFunction(() => !history.state?.recordSheet);
    }
    await page.getByRole("button", { name: "Log water", exact: true }).click();
    await page.getByRole("dialog", { name: "WATER", exact: true }).getByRole("button", { name: "+8 oz", exact: true }).click();
    await page.locator(".redesign-toast").waitFor();
    await page.screenshot({ path: `${out}/${width}-water-confirmation.png` });
    const bounds = await page.evaluate(() => ({ receipt: document.querySelector(".redesign-toast").getBoundingClientRect().bottom, nav: document.querySelector(".shell-nav").getBoundingClientRect().top }));
    assert.ok(bounds.receipt <= bounds.nav);
    await page.getByRole("button", { name: "UNDO", exact: true }).click();
    await page.locator(".redesign-toast").waitFor({ state: "detached" });
    await page.getByRole("button", { name: "BODY", exact: true }).click();
    await page.getByRole("button", { name: "WEIGHT HISTORY", exact: true }).waitFor();
    await page.evaluate(() => { for (const animation of document.getAnimations()) if (animation.effect?.getComputedTiming().iterations !== Infinity) animation.finish(); window.scrollTo(0, 0); });
    assert.equal(await page.locator(".body-home input[type=number]:visible").count(), 0);
    await page.screenshot({ path: `${out}/${width}-body.png`, fullPage: true });
    await page.getByRole("button", { name: "MEASUREMENTS", exact: true }).click();
    await page.getByRole("spinbutton", { name: "Inches", exact: true }).waitFor();
    await page.screenshot({ path: `${out}/${width}-measurements.png`, fullPage: true });
    await page.getByRole("button", { name: "BACK TO BODY", exact: true }).click();
    await page.getByRole("button", { name: "PHOTOS", exact: true }).click();
    await page.getByRole("heading", { name: "Progress photos", exact: true }).waitFor();
    await page.screenshot({ path: `${out}/${width}-photos.png`, fullPage: true });
    await page.getByRole("button", { name: "BACK TO BODY", exact: true }).click();
    await page.getByRole("button", { name: "TRAIN", exact: true }).click();
    for (const view of ["WORKOUT", "HISTORY", "RECORDS"]) {
      await page.getByRole("button", { name: view, exact: true }).click();
      await page.evaluate(() => { for (const a of document.getAnimations()) if (a.effect?.getComputedTiming().iterations !== Infinity) a.finish(); });
      await page.screenshot({ path: `${out}/${width}-train-${view.toLowerCase()}.png`, fullPage: true });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    }
    await page.getByRole("button", { name: "COMMAND", exact: true }).click();
    await page.getByRole("searchbox", { name: "Find a screen or action" }).waitFor();
    await page.evaluate(() => { for (const a of document.getAnimations()) if (a.effect?.getComputedTiming().iterations !== Infinity) a.finish(); window.scrollTo(0, 0); });
    await page.screenshot({ path: `${out}/${width}-command.png`, fullPage: true });
    await page.getByRole("searchbox", { name: "Find a screen or action" }).fill("Shift dinner");
    await page.getByRole("button", { name: "Shift dinner Saved meal · choose servings", exact: true }).click();
    await page.getByRole("dialog", { name: "SERVINGS", exact: true }).waitFor();
    await page.screenshot({ path: `${out}/${width}-command-meal-search.png` });
    await page.getByRole("dialog").getByRole("button", { name: "CLOSE", exact: true }).click();
    await page.waitForFunction(() => !history.state?.recordSheet);
    const search = page.getByRole("searchbox", { name: "Find a screen or action" });
    await search.fill("hidden features");
    await page.getByRole("button", { name: /^HIDDEN FEATURES / }).click();
    for (const name of ["Minimum Day", "Small Steps", "Online food lookup"]) assert.equal(await page.getByRole("checkbox", { name: `Show ${name}`, exact: true }).isChecked(), false);
    await page.screenshot({ path: `${out}/${width}-hidden-features.png`, fullPage: true });
    await search.fill("protein only");
    await page.getByRole("button", { name: /^PROTEIN ONLY / }).click();
    await page.getByRole("dialog", { name: "PROTEIN ONLY", exact: true }).waitFor();
    await page.screenshot({ path: `${out}/${width}-protein-only.png` });
    await page.getByRole("dialog").getByRole("button", { name: "CLOSE", exact: true }).click();
    await page.waitForFunction(() => !history.state?.recordSheet);
    await search.fill("backup");
    await page.getByRole("button", { name: /^BACKUP & RECOVERY / }).click();
    await page.getByText("RESTORE — REPLACES ALL DATA", { exact: true }).waitFor();
    await page.screenshot({ path: `${out}/${width}-backup-recovery.png`, fullPage: true });
    await page.getByRole("button", { name: "TODAY", exact: true }).click();
    await page.evaluate(async () => { await navigator.serviceWorker.ready; });
    await page.reload();
    await page.getByRole("button", { name: "Log water", exact: true }).waitFor();
    await context.setOffline(true);
    await page.reload();
    await page.getByRole("button", { name: "Log water", exact: true }).click();
    await page.getByRole("dialog", { name: "WATER", exact: true }).getByRole("button", { name: "+12 oz", exact: true }).click();
    await page.locator(".redesign-toast").waitFor();
    await page.reload();
    await page.getByRole("button", { name: "Log water", exact: true }).waitFor();
    await page.getByRole("button", { name: "Water 12 oz, explore records", exact: true }).waitFor();
    assert.deepEqual(errors, []);
    evidence.push({ width, modes: 4, checkInSheet: true, visibleReceipt: bounds, offlineColdReload: true, pageErrors: errors });
    await context.close();
    console.log(`PASS ${width}: TODAY order, four modes, check-in sheet, visible water undo, offline cold reload`);
  }
  await writeFile(`${out}/final-acceptance.json`, JSON.stringify({ inspectedHead, browser: "Chromium", timezone: "America/Chicago", reducedMotion: true, syntheticDataOnly: true, evidence }, null, 2) + "\n");
} finally { await browser.close(); await server.close(); }
