#!/usr/bin/env node
/**
 * GRAYSON-OPEN-LIBRARY-001: regenerates src/data/openExercises.json from free-exercise-db at one pinned commit.
 *
 *   node scripts/build-open-exercises.mjs            fetch the pinned commit and write the file
 *   node scripts/build-open-exercises.mjs <file>     map a local copy of dist/exercises.json instead (offline)
 *
 * Source: https://github.com/yuhonas/free-exercise-db, released under the Unlicense (public domain). The data only,
 * never its pictures. An update is one reviewed PR: change PINNED_COMMIT, run this, review the diff.
 *
 * It keeps every category (stretching and cardio are hidden in the app until he shows them), drops the fields the
 * app doesn't use, names the equipment the way BEYOND does, and leaves the muscle mapping to the app's one table
 * (src/domain/workout/openLibrary.ts), so the mapping is tested against every value in the file.
 */
import { readFile, writeFile } from "node:fs/promises";

export const PINNED_COMMIT = "f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5";
const SOURCE = `https://raw.githubusercontent.com/yuhonas/free-exercise-db/${PINNED_COMMIT}`;
const OUT = new URL("../src/data/openExercises.json", import.meta.url);

/** The dataset's equipment, in BEYOND's words (deriveIncrementLbs reads Barbell, Dumbbell, Cable, Machine). */
const EQUIPMENT = {
  barbell: "Barbell", dumbbell: "Dumbbell", cable: "Cable", machine: "Machine", kettlebells: "Kettlebell",
  bands: "Band", "medicine ball": "Medicine Ball", "exercise ball": "Exercise Ball", "foam roll": "Foam Roller",
  "e-z curl bar": "EZ Bar", "body only": "Bodyweight", other: "Other",
};

async function main() {
  const local = process.argv[2];
  const [raw, licence] = local
    ? [await readFile(local, "utf8"), null]
    : await Promise.all([fetchText(`${SOURCE}/dist/exercises.json`), fetchText(`${SOURCE}/LICENSE.md`)]);
  if (licence !== null && !licence.startsWith("This is free and unencumbered software released into the public domain.")) {
    throw new Error("The pinned commit's licence is not the Unlicense. Stop and ask Gavin (GRAYSON-OPEN-LIBRARY-001).");
  }
  const source = JSON.parse(raw);
  const exercises = source.map((x) => {
    if (!/^[A-Za-z0-9_-]+$/.test(x.id)) throw new Error(`Unexpected id: ${x.id}`);
    const equipment = x.equipment === null ? "Bodyweight" : EQUIPMENT[x.equipment];
    if (!equipment) throw new Error(`Unmapped equipment: ${x.equipment}`);
    if (!x.primaryMuscles?.length) throw new Error(`No primary muscle: ${x.id}`);
    return {
      id: `fedb-${x.id}`,
      name: x.name.trim(),
      primary: x.primaryMuscles[0],
      secondary: [...x.primaryMuscles.slice(1), ...x.secondaryMuscles],
      equipment,
      level: x.level,
      category: x.category,
      steps: x.instructions.map((s) => s.trim()).filter(Boolean),
    };
  }).sort((a, b) => a.id.localeCompare(b.id));
  const file = {
    source: "free-exercise-db (https://github.com/yuhonas/free-exercise-db)",
    commit: PINNED_COMMIT,
    licence: "Unlicense (public domain)",
    note: "Generated by scripts/build-open-exercises.mjs. Do not edit by hand.",
    exercises,
  };
  await writeFile(OUT, `${JSON.stringify(file)}\n`);
  console.log(`Wrote ${exercises.length} exercises from ${PINNED_COMMIT}.`);
}

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
}

await main();
