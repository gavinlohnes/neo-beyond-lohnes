import { afterEach, expect, it } from "vitest";
import { cleanup, render } from "vitest-browser-react";
import { page } from "vitest/browser";
import axe from "axe-core";
import { MealPlanPanel } from "../../src/ui/screens/body/MealPlanPanel";
import { createSavedMeal } from "../../src/application/nutritionCommands";
import { db } from "../../src/persistence/db";
afterEach(cleanup);
it("drafts, swaps and clears at 360px; saves a grocery note only on confirmation, never food", async () => {
  await page.viewport(360, 800);
  for (let i = 0; i < 5; i++) await createSavedMeal({ name: `Synthetic meal ${i}`, calories: 500, proteinG: 40 + i, carbsG: 30, fatG: 10 });
  const events = await db.events.count();
  const screen = await render(<MealPlanPanel now={new Date(2026, 10, 2, 17)} />);
  await screen.getByRole("button", { name: "PLAN MY MEALS", exact: true }).click();
  await expect.poll(() => screen.container.querySelectorAll("fieldset").length).toBe(3);
  const first = screen.getByRole("combobox", { name: "2026-11-02 Breakfast", exact: true });
  const option = first.element().querySelectorAll("option")[1]!.value;
  await first.selectOptions(option);
  await expect.element(first).toHaveValue(option);
  await first.selectOptions("");
  await expect.element(first).toHaveValue("");
  await screen.getByRole("button", { name: "SAVE GROCERY LIST", exact: true }).click();
  await expect.element(screen.getByRole("button", { name: "CONFIRM SAVE NOTE" })).toBeVisible();
  expect(await db.captureItems.count()).toBe(0);
  await screen.getByRole("button", { name: "CANCEL", exact: true }).click();
  expect(await db.captureItems.count()).toBe(0);
  await screen.getByRole("button", { name: "SAVE GROCERY LIST", exact: true }).click();
  await screen.getByRole("button", { name: "CONFIRM SAVE NOTE" }).click();
  await expect.element(screen.getByRole("status")).toHaveTextContent("Grocery list saved");
  expect(await db.captureItems.count()).toBe(1);
  expect(await db.events.count()).toBe(events);
  expect((await axe.run(screen.container)).violations).toEqual([]);
  expect(document.documentElement.scrollWidth).toBeLessThanOrEqual(360);
});
