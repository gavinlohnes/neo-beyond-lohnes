beforeEach(async () => { window.history.replaceState(null, "", window.location.pathname); vi.useFakeTimers({ toFake: ["Date"] }); vi.setSystemTime(new Date(2026, 9, 12, 17, 10)); dayId = (await startDay()).id; });
