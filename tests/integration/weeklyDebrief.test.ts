import { afterEach, expect, it, vi } from "vitest";
import { startDay, setWorkContext, markWorkEnded, logSleep, logWater, logBodyweight } from "../../src/application/commands";
import { createSavedMeal, logMeal } from "../../src/application/nutritionCommands";
import { startWorkout, logSet, completeWorkout } from "../../src/application/trainCommands";
import { createObligation, satisfyObligation } from "../../src/application/intentCommands";
import { getWeeklyDashboard } from "../../src/application/weeklyDashboardQueries";
import { getWeekInNumbers } from "../../src/application/weeklyDebriefQueries";
import { db } from "../../src/persistence/db";
afterEach(() => vi.useRealTimers());
it("reuses canonical corrected evidence for sets, volume, commitments and worked records, without writing", async () => {
  vi.useFakeTimers({ toFake: ["Date"] }); vi.setSystemTime(new Date(2026, 9, 26, 18));
  const day = await startDay(); await setWorkContext(day.id, "WORK", "MANUAL");
  await markWorkEnded(day.id); await logSleep(day.id, 360); await logWater(day.id, 64); await logBodyweight(day.id, 200);
  const meal = await createSavedMeal({ name: "Synthetic meal", calories: 600, proteinG: 50, carbsG: 30, fatG: 10 });
  await logMeal(day.id, meal.id);
  const session = await startWorkout(day.id, "A", "STANDARD");
  await logSet(day.id, session.id, "machine-chest-press", 1, 100, 10);
  await completeWorkout(day.id, session.id, "STANDARD", "COMPLETED");
  const done = await createObligation({ title: "Synthetic done" }); await satisfyObligation(done.id);
  await createObligation({ title: "Synthetic still open" });
  vi.setSystemTime(new Date(2026, 10, 2, 18)); await startDay();
  const events = await db.events.toArray();
  const result = await getWeekInNumbers(await getWeeklyDashboard(0));
  expect(result.calories).toEqual({ average: 600, days: 1 });
  expect(result.protein).toEqual({ average: 50, days: 1 });
  expect(result.training).toMatchObject({ sessions: 1, sets: 1, volume: 1000, days: 1 });
  expect(result.commitments).toEqual({ done: 1, days: 1, open: 1 });
  expect(result.shifts.worked).toBe(1);
  expect(await db.events.toArray()).toEqual(events);
});
